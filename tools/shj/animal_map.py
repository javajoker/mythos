"""Animal map (Method G, stages G1–G2): match every book creature to real animals by description, then turn the
best matches into a vote over world regions for each section.

  rarity weight   w(t) = log10(N_animals / df(t)) + 0.05          (df = animals carrying tag t)
  coverage        cov  = Σ_{t ∈ C∩A} w(t) / Σ_{t ∈ C} w(t)        (share of the description the animal explains)
  kind check      a bird must have wings/bird body, a fish must be aquatic/marine/fish-bodied; otherwise cov × 0.5
  body check      if the text gives a body analogy and the animal shares none of them, cov × 0.6
A match counts for the map only if cov ≥ 0.5 and at least 2 tags overlap. Its regions share the vote equally.

Output: projects/shanhaijing/data/derived/animal-map.jsonl, animal-map.md
"""
import json
import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CREATURES = ROOT / "projects/shanhaijing/data/derived/creatures.jsonl"
ANIMALS = ROOT / "projects/shanhaijing/data/world/animals.jsonl"
OUT = ROOT / "projects/shanhaijing/data/derived"
GENERIC = {"vocal", "aquatic"}
MIN_COV, MIN_OVERLAP = 0.5, 2


def load_animals():
    animals = [json.loads(l) for l in ANIMALS.open() if l.strip()]
    df = Counter(t for a in animals for t in set(a["tags"]))
    n = len(animals)
    w = defaultdict(lambda: math.log10(n) + 0.05, {t: math.log10(n / c) + 0.05 for t, c in df.items()})
    for g in GENERIC:
        w[g] = min(w[g], 0.05)
    return animals, w


def match(tags, kind, animals, w, top=3):
    C = set(tags)
    denom = sum(w[t] for t in C) or 1
    bodies = {t for t in C if t.startswith("body_")}
    res = []
    for a in animals:
        A = set(a["tags"])
        ov = C & A
        cov = sum(w[t] for t in ov) / denom
        if kind == "bird" and not (A & {"wings", "body_bird", "body_fowl", "body_duck", "body_owl", "body_crow", "body_crane"}):
            cov *= 0.5
        if kind == "fish" and not (A & {"aquatic", "marine", "body_fish"}):
            cov *= 0.5
        if bodies and not (bodies & A):
            cov *= 0.6
        res.append((round(cov, 3), sorted(ov), a))
    res.sort(key=lambda r: -r[0])
    return res[:top]


def main():
    animals, w = load_animals()
    creatures = [json.loads(l) for l in CREATURES.open()]
    rows, votes = [], defaultdict(Counter)
    for c in creatures:
        best = match(c["tags"], c["kind"], animals, w)
        cov, ov, a = best[0]
        ok = cov >= MIN_COV and len(ov) >= MIN_OVERLAP
        rows.append({"cid": c["cid"], "entry_id": c["entry_id"], "section": c["section"], "book": c["book"],
                     "name_display_only": c["name_display_only"], "tags": c["tags"],
                     "matches": [{"animal": x[2]["id"], "en": x[2]["en"], "coverage": x[0], "shared": x[1],
                                  "regions": x[2]["regions"]} for x in best], "accepted": ok})
        if ok:
            for r in a["regions"]:
                votes[(c["book"], c["section"])][r] += cov / len(a["regions"])
    with (OUT / "animal-map.jsonl").open("w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    acc = [r for r in rows if r["accepted"]]
    lines = ["# 動物地圖（方法 G）/ Animal map (Method G)", "",
             f"Generated by `tools/shj/animal_map.py` from {len(rows)} tagged creature descriptions "
             f"({len(acc)} accepted at coverage ≥ {MIN_COV} with ≥ {MIN_OVERLAP} shared tags) against "
             f"{len(animals)} real animals. Names are masked; matching uses descriptions only.", "",
             "## 1. 最強的描述比對 / Strongest description matches", "",
             "| 條目 / entry | 書中名（僅供閱讀）| 最佳真實動物 / best real animal | 覆蓋 / coverage | 共同特徵 / shared | 分佈 / range |",
             "|---|---|---|---|---|---|"]
    for r in sorted(acc, key=lambda r: -r["matches"][0]["coverage"])[:40]:
        m = r["matches"][0]
        lines.append(f"| `{r['entry_id']}` | {r['name_display_only']} | {m['en']} | {m['coverage']} | "
                     f"{', '.join(m['shared'])} | {' '.join(m['regions'][:8])}{'…' if len(m['regions']) > 8 else ''} |")
    lines += ["", "## 2. 各篇的動物分佈投票 / Regional vote per section", "",
              "Each accepted creature splits its coverage equally over its best animal's regions.", "",
              "| 書・篇 / section | 被接受的生物 / accepted | 前三地區 / top regions |", "|---|---|---|"]
    for (book, sec), v in sorted(votes.items(), key=lambda kv: kv[0]):
        n = sum(1 for r in acc if (r["book"], r["section"]) == (book, sec))
        top = ", ".join(f"{k} {x:.2f}" for k, x in v.most_common(3))
        lines.append(f"| {book}・{sec} | {n} | {top} |")
    total = Counter()
    for v in votes.values():
        total.update(v)
    lines += ["", "## 3. 全書合計 / Whole book", "", ", ".join(f"{k} {x:.2f}" for k, x in total.most_common(15))]
    (OUT / "animal-map.md").write_text("\n".join(lines) + "\n")
    print(f"{len(acc)}/{len(rows)} accepted; whole-book top regions: {total.most_common(6)}", file=sys.stderr)


if __name__ == "__main__":
    main()
