"""Whole-book river network of the 五藏山經 and its name-masked fingerprint (spec §7.2, task T-303).

Every 「X水出焉，而{dir}流注于Y」 becomes a directed edge X → Y carrying the source station and flow bearing.
Two fingerprints are produced, both *independent of what the rivers are called today*:

  1. Network fingerprint — the trunk (highest in-degree) and its main tributaries, with every name replaced by a
     code (T, A, B, …) so the shape can be compared blindly against real drainage basins.
  2. Section-side fingerprint — for each section, which receiving river its streams drain into and in which
     direction (e.g. "9 streams flow N into A" = the route runs along the south side of A).

Output: projects/shanhaijing/data/derived/river-graph.json, river-graph.md
"""
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DER = ROOT / "projects/shanhaijing/data/derived"
OPP = {"北": "南", "南": "北", "東": "西", "西": "東"}


def core(name: str) -> str:
    """渭水→渭, 麗𪊨之水→麗𪊨, 榖水→穀. Lakes/seas (澤, 海) are kept whole."""
    n = name.replace("榖", "穀").replace("雒", "洛").strip()
    if n.endswith(("澤", "海")) or n in ("河", "江"):
        return n
    n = re.sub(r"之水$", "", n)
    n = re.sub(r"水$", "", n)
    return {"大江": "江", "河水": "河", "江水": "江"}.get(n, n) or name


def main():
    stations = [json.loads(l) for l in (DER / "stations.jsonl").open()]
    edges = []
    for s in stations:
        for r in s["rivers"]:
            edges.append({"river": core(r["river"]), "to": core(r["to"]), "flow": r["flow"],
                          "source_station": s["name"], "entry_id": s["entry_id"], "section": s["section"],
                          "book": s["book"]})
    indeg = Counter(e["to"] for e in edges)
    tribs = defaultdict(list)
    for e in edges:
        tribs[e["to"]].append(e)
    rank = [n for n, _ in indeg.most_common() if not n.endswith(("海", "澤"))]
    code = {n: ("T" if i == 0 else chr(ord("A") + i - 1)) for i, n in enumerate(rank[:12])}

    def c(n):
        return code.get(n, "·")

    (DER / "river-graph.json").write_text(json.dumps({"edges": edges, "in_degree": indeg, "codes": code},
                                                     ensure_ascii=False, indent=1))
    lines = ["# 山經水系圖 / Mountain-Classic river network", "",
             "Generated by `tools/shj/river_graph.py`. Names are folded only for spelling (渭水→渭, 雒→洛, 榖→穀).", "",
             "## 1. 名稱遮蔽的網路指紋 / Name-masked network fingerprint", "",
             "Codes replace names so the shape can be compared blindly with real basins. "
             "`←` = flows into; direction = the text's stated flow direction of the tributary.", "",
             "| code | in-degree | tributaries that are themselves receivers (code: flow dir × count) |", "|---|---|---|"]
    for n in rank[:12]:
        sub = Counter((c(e["river"]), e["flow"]) for e in tribs[n] if e["river"] in code)
        dirs = Counter(e["flow"] for e in tribs[n])
        lines.append(f"| {c(n)} | {indeg[n]} | " + ", ".join(f"{k} ({d}×{v})" for (k, d), v in sub.items())
                     + f" — all inflows by direction: {dict(dirs)} |")
    lines += ["", "### 主要接收河之間的關係 / Links between the main receivers", ""]
    for e in edges:
        if e["river"] in code and e["to"] in code:
            lines.append(f"- {c(e['river'])} → {c(e['to'])}, flowing {e['flow']} (`{e['entry_id']}`)")
    lines += ["", "### 解碼表（只供事後核對，比對時不得使用）/ Key (for audit only — not used for matching)", ""]
    lines += [f"- {v} = {k}" for k, v in code.items()]

    lines += ["", "## 2. 各篇的流域側位 / Which side of which river each section runs on", "",
              "If most streams of a section flow N into X, the route runs along X's south side (and so on).", "",
              "| section | dominant receivers (code, flow, count) | reading |", "|---|---|---|"]
    by_sec = defaultdict(list)
    for e in edges:
        by_sec[(e["book"], e["section"])].append(e)
    for (book, sec), es in by_sec.items():
        cnt = Counter((c(e["to"]), e["flow"]) for e in es if e["to"] in code)
        top = cnt.most_common(3)
        reading = "; ".join(f"route on the {OPP.get(d, '?')} side of {k}" for (k, d), n in top
                            if n >= 2 and d in OPP)
        lines.append(f"| {book}・{sec} | " + ", ".join(f"{k} {d}×{n}" for (k, d), n in top) + f" | {reading} |")
    (DER / "river-graph.md").write_text("\n".join(lines) + "\n")
    print(f"{len(edges)} edges; trunk = {rank[0]} (in-degree {indeg[rank[0]]})")


if __name__ == "__main__":
    main()
